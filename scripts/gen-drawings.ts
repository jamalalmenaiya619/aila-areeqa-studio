// Generates src/study/drawings.generated.tsx from the legacy drawing code (identical shapes and labels;
// only colors move to tokens). Parametric drawings (Al-Qatt builder, weave grid) are hand-ported in drawings.tsx.
import { writeFileSync } from "node:fs";
import { ROOT, loadLegacyDrawings, retoken } from "./lib-legacy.ts";

const ATTR: Record<string, string> = {
  "stroke-width": "strokeWidth", "font-family": "fontFamily", "font-size": "fontSize", "text-anchor": "textAnchor",
  "fill-opacity": "fillOpacity", "stroke-dasharray": "strokeDasharray", "stroke-linecap": "strokeLinecap",
};
function toJSX(svg: string) {
  let s = svg.replace(/\s+/g, " ").replace(/> </g, "><").trim();
  s = s.replace(/ ([a-z-]+)="/g, (m, a) => (ATTR[a] ? ` ${ATTR[a]}="` : m));
  if (/[{}]/.test(s.replace(/<text[^>]*>[^<]*<\/text>/g, ""))) throw new Error("Unexpected brace in SVG");
  s = s.replace(/>([^<]*[{}][^<]*)</g, (m, t) => `>{${JSON.stringify(t)}}<`);
  return s;
}
const { SVG } = loadLegacyDrawings();
const PARAMETRIC = new Set(["qattMono", "qattColor", "qattBlank"]);
let out = `// GENERATED by scripts/gen-drawings.ts from legacy/studybook/index.html. Do not edit by hand.\n/* eslint-disable */\nimport type { ReactElement } from "react";\n\nexport const STATIC_DRAWINGS: Record<string, () => ReactElement> = {\n`;
for (const [k, fn] of Object.entries(SVG)) {
  if (PARAMETRIC.has(k)) continue;
  out += `  ${k}: () => (${toJSX(retoken(fn()))}),\n`;
}
out += "};\n";
writeFileSync(ROOT + "src/study/drawings.generated.tsx", out);
console.log(`Drawings: ${Object.keys(SVG).length - PARAMETRIC.size} generated, ${PARAMETRIC.size} parametric (hand-ported).`);
