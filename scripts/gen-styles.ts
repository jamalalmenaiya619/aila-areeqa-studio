// Ports the legacy Study Book and Intel CSS into scoped stylesheets. Layout rules are copied as written;
// only color variables and fonts are renamed to the brand tokens. Output: src/styles/*.generated.css
import { readFileSync, writeFileSync } from "node:fs";
import { ROOT, VAR_MAP } from "./lib-legacy.ts";

const INTEL_MAP: Record<string, string> = {
  "--muted": "--ink-soft", "--brass": "--gold", "--navy-ink": "--on-ink", "--navy": "--ink",
  "--ok": "--st-confirmed", "--warn": "--st-tension", "--bad": "--st-down", "--new": "--st-new",
  "--display": "--f-display", "--body": "--f-body", "--mono": "--f-mono",
};
const HEX_CSS: Record<string, string> = { "rgba(10, 12, 18, .78)": "var(--overlay)" };

function styleOf(file: string) {
  const html = readFileSync(ROOT + file, "utf8");
  const blocks = [...html.matchAll(/<style>([\s\S]*?)<\/style>/g)].map((m) => m[1]);
  return blocks[blocks.length - 1]; // the page's own stylesheet (the published file has a host style block first)
}
// Split CSS into top-level statements, respecting nested braces.
function statements(css: string) {
  const out: string[] = []; let depth = 0, start = 0;
  for (let i = 0; i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}") { depth--; if (depth === 0) { out.push(css.slice(start, i + 1).trim()); start = i + 1; } }
  }
  return out.filter(Boolean);
}
const stripComments = (s: string) => s.replace(/\/\*[\s\S]*?\*\//g, "");

function scope(css: string, root: string, drop: RegExp, rootSel: RegExp): string {
  return statements(css).map((st) => {
    const open = st.indexOf("{");
    const head = st.slice(0, open).trim(), body = st.slice(open + 1, -1);
    if (head.startsWith("@keyframes")) return st;
    if (head.startsWith("@media")) {
      const inner = scope(body, root, drop, rootSel);
      return inner.trim() ? `${head} {\n${inner}\n}` : "";
    }
    const sels = head.split(",").map((s) => s.trim()).filter((s) => !drop.test(s));
    if (!sels.length) return "";
    const scoped = sels.map((s) => (rootSel.test(s) ? root : s.startsWith(":focus-visible") ? `${root} ${s}` : `${root} ${s}`));
    return `${scoped.join(", ")} {${body}}`;
  }).filter(Boolean).join("\n");
}
function rename(css: string, map: Record<string, string>) {
  let s = css.replace(/var\((--[a-z-]+)\)/g, (m, v) => (map[v] ? `var(${map[v]})` : m));
  for (const [k, v] of Object.entries(HEX_CSS)) s = s.split(k).join(v);
  if (/#[0-9a-fA-F]{3,6}\b/.test(s)) throw new Error("A fixed color is left in the ported CSS: " + s.match(/#[0-9a-fA-F]{3,6}\b/)![0]);
  return s;
}
const head = (src: string) => `/* GENERATED by scripts/gen-styles.ts from ${src}. Do not edit by hand. Layout as written; colors and fonts use tokens.css. */\n`;

// Study Book: drop :root token blocks, html/body sizing, #app wrappers and the safe-area strip.
const sb = rename(scope(stripComments(styleOf("legacy/studybook/index.html")), ".sb", /^(:root|\*|html|#app|body::before)/, /^body$/), VAR_MAP);
writeFileSync(ROOT + "src/styles/studybook.generated.css", head("legacy/studybook/index.html") + sb + "\n");
// Intel: same, scoped to .intel.
const intel = rename(scope(stripComments(styleOf("legacy/intel/battlefield-published-run17.html")), ".intel", /^(:root|\*)/, /^body$/), INTEL_MAP);
writeFileSync(ROOT + "src/styles/intel.generated.css", head("legacy/intel/battlefield-published-run17.html") + intel + "\n");
console.log("Styles: Study Book and Intel ported.");
